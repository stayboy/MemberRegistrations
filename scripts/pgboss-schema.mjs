#!/usr/bin/env node
/**
 * Regenerates the vendored pg-boss DDL in `src/db/pgboss-schema.ts`.
 *
 * pg-boss ships its own `pgboss` schema. AGENTS 12 keeps one tracked migration
 * runner as the only thing that mutates the database, so `0031_pgboss_schema`
 * carries the release's DDL and pg-boss runs with `migrate: false`. That puts
 * the schema in our tree, where it can silently drift from the dependency:
 * this script is the only supported way to change it.
 *
 *   node scripts/pgboss-schema.mjs            # rewrite the vendored file
 *   node scripts/pgboss-schema.mjs --check    # fail on a diff
 *
 * An upgrade is therefore: bump the exact pin, run this, run `pg-boss doctor`
 * against a migrated database, commit the diff (round doc decision 2).
 *
 * `plans create` is used rather than `plans migrate --dry-run`: the migrate
 * plan inlines `CREATE INDEX CONCURRENTLY`, which cannot run inside the
 * transaction the tracked runner wraps every migration in. `create` emits the
 * same objects for a fresh schema without the concurrent statements.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const VENDORED_PATH = resolve(here, '../src/db/pgboss-schema.ts');

const SCHEMA = 'pgboss';

function pgBossPaths() {
  const require = createRequire(import.meta.url);
  const manifestPath = require.resolve('pg-boss/package.json');
  return {
    manifestPath,
    cliPath: resolve(dirname(manifestPath), 'dist/cli.js'),
    manifest: JSON.parse(readFileSync(manifestPath, 'utf8')),
  };
}

/** The raw CLI output, header and transaction wrapper included. */
export function readPlans() {
  const { cliPath } = pgBossPaths();
  return execFileSync(process.execPath, [cliPath, 'plans', 'create', '--schema', SCHEMA], {
    encoding: 'utf8',
  });
}

/**
 * The DDL the tracked runner applies. The CLI's own `BEGIN`/`COMMIT` and its
 * transaction-scoped advisory lock are dropped: `migrate()` already wraps the
 * migration (and takes its own lock), and a nested `COMMIT` would end the
 * runner's transaction early.
 */
export function extractSql(raw) {
  const lines = raw.split(/\r?\n/).map((line) => line.replace(/[ \t]+$/, ''));
  const start = lines.findIndex((line) => line.startsWith('CREATE SCHEMA IF NOT EXISTS '));
  const end = lines.findLastIndex((line) =>
    /^INSERT INTO \S+\.version\(version\) VALUES \('\d+'\);$/.test(line),
  );
  if (start === -1 || end === -1 || end <= start) {
    throw new Error('pg-boss plans create did not produce the shape this script expects');
  }

  const kept = [];
  for (const line of lines.slice(start, end + 1)) {
    if (line === '' && kept.at(-1) === '') continue;
    kept.push(line);
  }
  return kept.join('\n');
}

export function renderModule(sql, { packageVersion, schemaVersion }) {
  return `// Generated by scripts/pgboss-schema.mjs from pg-boss ${packageVersion} (pgboss schema ${schemaVersion}).
// Do not edit by hand: run \`node scripts/pgboss-schema.mjs\`.
//
// The tracked migration runner applies this DDL once, inside a transaction, and
// pg-boss runs with \`migrate: false\` (AGENTS 12). \`pg-boss doctor\` on a migrated
// database and tests/db/pgboss-schema.test.ts fail when this file drifts from the
// pinned release, so an upgrade is a bump, a regenerate and a doctor run.
export const PGBOSS_PACKAGE_VERSION = '${packageVersion}';
export const PGBOSS_SCHEMA_VERSION = ${schemaVersion};
export const PGBOSS_SCHEMA_SQL = String.raw\`${sql}\`;
`;
}

/** Everything the vendored file should contain, from the installed release. */
export function buildVendored() {
  const { manifest } = pgBossPaths();
  const schemaVersion = Number(manifest.pgboss?.schema);
  if (!Number.isInteger(schemaVersion)) {
    throw new Error(`pg-boss ${manifest.version} does not declare its schema version`);
  }
  return {
    packageVersion: manifest.version,
    schemaVersion,
    sql: extractSql(readPlans()),
  };
}

function main() {
  const generated = buildVendored();
  const text = renderModule(generated.sql, generated);
  const check = process.argv.includes('--check');

  if (check) {
    const committed = readFileSync(VENDORED_PATH, 'utf8');
    if (committed !== text) {
      console.error(
        `pg-boss ${generated.packageVersion} DDL differs from src/db/pgboss-schema.ts; run \`node scripts/pgboss-schema.mjs\` and commit the result`,
      );
      process.exit(1);
    }
    console.log(`pg-boss ${generated.packageVersion} DDL matches src/db/pgboss-schema.ts`);
    return;
  }

  writeFileSync(VENDORED_PATH, text);
  console.log(
    `wrote src/db/pgboss-schema.ts from pg-boss ${generated.packageVersion} (schema ${generated.schemaVersion})`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
